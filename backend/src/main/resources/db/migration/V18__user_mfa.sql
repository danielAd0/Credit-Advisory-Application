-- =====================================================================
-- V18: two-step sign-in (MFA) with an authenticator app.
--
-- Kept out of the users table on purpose: setting up MFA must not change
-- the account version (that would sign the user's sessions out), while an
-- admin reset of MFA does so explicitly.
-- =====================================================================

CREATE TABLE user_mfa
(
    user_id          BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    -- AES-256-GCM under MFA_ENCRYPTION_KEY: 1 version byte + 12 nonce + 20 secret + 16 tag.
    secret_encrypted BYTEA       NOT NULL,
    -- The last 30-second step whose code was accepted. A code is never accepted twice.
    last_used_step   BIGINT,
    enabled_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_user_mfa_secret_length CHECK (octet_length(secret_encrypted) >= 29)
);

CREATE TABLE user_mfa_recovery_codes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES user_mfa (user_id) ON DELETE CASCADE,
    -- SHA-256 of the code; the code itself is shown to the user once and never stored.
    code_hash  CHAR(64)    NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_user_mfa_recovery_codes UNIQUE (user_id, code_hash),
    CONSTRAINT ck_user_mfa_recovery_codes_hash CHECK (code_hash ~ '^[0-9a-f]{64}$')
);
