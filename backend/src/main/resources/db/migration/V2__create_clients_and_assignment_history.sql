
CREATE TABLE clients
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_number_hash        BYTEA        NOT NULL,
    id_number_encrypted   BYTEA        NOT NULL,
    id_number_last4       VARCHAR(4)   NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    email                 VARCHAR(254),
    phone                 VARCHAR(20),
    current_consultant_id BIGINT REFERENCES consultants (id),
    version               BIGINT       NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_clients_id_number_hash UNIQUE (id_number_hash),
    CONSTRAINT ck_clients_id_hash_length CHECK (octet_length(id_number_hash) = 32),
    CONSTRAINT ck_clients_id_encrypted_length CHECK (octet_length(id_number_encrypted) >= 29),
    CONSTRAINT ck_clients_id_last4 CHECK (id_number_last4 ~ '^[0-9]{4}$'),
    CONSTRAINT ck_clients_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT ck_clients_last_name_not_blank CHECK (btrim(last_name) <> ''),
    CONSTRAINT ck_clients_email_format CHECK (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_clients_phone_format CHECK (phone IS NULL OR phone ~ '^\+[1-9][0-9]{7,14}$')
);

CREATE INDEX ix_clients_current_consultant ON clients (current_consultant_id);
CREATE INDEX ix_clients_name ON clients (lower(last_name), lower(first_name));
CREATE INDEX ix_clients_unassigned ON clients (id) WHERE current_consultant_id IS NULL;

CREATE TRIGGER trg_clients_updated_at
    BEFORE UPDATE ON clients
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


CREATE FUNCTION ensure_assigned_consultant_active() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    consultant_status VARCHAR(16);
BEGIN
    IF NEW.current_consultant_id IS NOT NULL
        AND (TG_OP = 'INSERT' OR NEW.current_consultant_id IS DISTINCT FROM OLD.current_consultant_id) THEN

        SELECT status INTO consultant_status
        FROM consultants
        WHERE id = NEW.current_consultant_id
            FOR SHARE;

        IF consultant_status IS DISTINCT FROM 'ACTIVE' THEN
            RAISE EXCEPTION 'Client cannot be assigned to consultant %: consultant is not ACTIVE',
                NEW.current_consultant_id
                USING ERRCODE = 'check_violation',
                    CONSTRAINT = 'ck_clients_consultant_active';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_clients_consultant_active
    BEFORE INSERT OR UPDATE OF current_consultant_id ON clients
    FOR EACH ROW EXECUTE FUNCTION ensure_assigned_consultant_active();


CREATE TABLE client_assignment_history
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id          BIGINT       NOT NULL REFERENCES clients (id),
    from_consultant_id BIGINT REFERENCES consultants (id),
    to_consultant_id   BIGINT REFERENCES consultants (id),
    change_type        VARCHAR(16)  NOT NULL,
    reason             VARCHAR(500) NOT NULL,
    transfer_batch_id  UUID,
    changed_by_user_id BIGINT       NOT NULL REFERENCES users (id),
    changed_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_assignment_history_change_type
        CHECK (change_type IN ('IMPORT', 'MANUAL', 'TRANSFER', 'BULK_TRANSFER', 'UNASSIGN')),
    CONSTRAINT ck_assignment_history_reason_not_blank CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_assignment_history_changes_something
        CHECK (from_consultant_id IS DISTINCT FROM to_consultant_id),
    CONSTRAINT ck_assignment_history_bulk_has_batch
        CHECK (change_type <> 'BULK_TRANSFER' OR transfer_batch_id IS NOT NULL)
);

CREATE INDEX ix_assignment_history_client ON client_assignment_history (client_id, changed_at DESC);
CREATE INDEX ix_assignment_history_from ON client_assignment_history (from_consultant_id);
CREATE INDEX ix_assignment_history_to ON client_assignment_history (to_consultant_id);
CREATE INDEX ix_assignment_history_batch ON client_assignment_history (transfer_batch_id)
    WHERE transfer_batch_id IS NOT NULL;

CREATE TRIGGER trg_assignment_history_no_update
    BEFORE UPDATE OR DELETE ON client_assignment_history
    FOR EACH ROW EXECUTE FUNCTION reject_modification();

CREATE TRIGGER trg_assignment_history_no_truncate
    BEFORE TRUNCATE ON client_assignment_history
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();
