-- =====================================================================
-- V3: Excel import jobs, staged rows and row-level errors
-- =====================================================================

-- One uploaded workbook. Created at preview, committed at confirm.
CREATE TABLE import_jobs
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name             VARCHAR(255) NOT NULL,
    -- SHA-256 of the uploaded bytes, lower-case hex. Binds confirm to the exact file.
    file_digest           VARCHAR(64)  NOT NULL,
    file_size_bytes       BIGINT       NOT NULL,
    sheet_name            VARCHAR(100),
    state                 VARCHAR(16)  NOT NULL,
    allow_new_consultants BOOLEAN      NOT NULL DEFAULT FALSE,
    uploaded_by_user_id   BIGINT       NOT NULL REFERENCES users (id),
    total_rows            INTEGER      NOT NULL DEFAULT 0,
    new_count             INTEGER      NOT NULL DEFAULT 0,
    update_count          INTEGER      NOT NULL DEFAULT 0,
    unchanged_count       INTEGER      NOT NULL DEFAULT 0,
    invalid_count         INTEGER      NOT NULL DEFAULT 0,
    conflict_count        INTEGER      NOT NULL DEFAULT 0,
    duplicate_count       INTEGER      NOT NULL DEFAULT 0,
    new_consultant_count  INTEGER      NOT NULL DEFAULT 0,
    applied_count         INTEGER      NOT NULL DEFAULT 0,
    stale_count           INTEGER      NOT NULL DEFAULT 0,
    expires_at            TIMESTAMPTZ  NOT NULL,
    committed_at          TIMESTAMPTZ,
    -- Personal data in import_rows is removed once the job is finished.
    personal_data_purged_at TIMESTAMPTZ,
    version               BIGINT       NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_import_jobs_digest CHECK (file_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_jobs_size CHECK (file_size_bytes > 0),
    CONSTRAINT ck_import_jobs_state CHECK (state IN ('PREVIEWED', 'COMMITTED', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_import_jobs_committed_at CHECK ((state = 'COMMITTED') = (committed_at IS NOT NULL)),
    CONSTRAINT ck_import_jobs_counts CHECK (
        total_rows >= 0 AND new_count >= 0 AND update_count >= 0 AND unchanged_count >= 0
            AND invalid_count >= 0 AND conflict_count >= 0 AND duplicate_count >= 0
            AND new_consultant_count >= 0 AND applied_count >= 0 AND stale_count >= 0
            AND new_count + update_count + unchanged_count + invalid_count
                    + conflict_count + duplicate_count = total_rows)
);

CREATE INDEX ix_import_jobs_digest ON import_jobs (file_digest);
CREATE INDEX ix_import_jobs_uploader ON import_jobs (uploaded_by_user_id, created_at DESC);
CREATE INDEX ix_import_jobs_open ON import_jobs (expires_at) WHERE state = 'PREVIEWED';

CREATE TRIGGER trg_import_jobs_updated_at
    BEFORE UPDATE ON import_jobs
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- One worksheet row as validated at preview time. Holds what confirm needs
-- so the file never has to be uploaded or stored twice.
CREATE TABLE import_rows
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id           BIGINT      NOT NULL REFERENCES import_jobs (id) ON DELETE CASCADE,
    -- Row number as the operator sees it in Excel (header is usually row 1).
    row_number              INTEGER     NOT NULL,
    action                  VARCHAR(16) NOT NULL,
    -- Personal data: nulled when the job is committed, expired or cancelled.
    id_number_hash          BYTEA,
    id_number_encrypted     BYTEA,
    first_name              VARCHAR(100),
    last_name               VARCHAR(100),
    email                   VARCHAR(254),
    phone                   VARCHAR(20),
    -- Kept after purge so the report stays readable.
    id_number_last4         VARCHAR(4),
    consultant_code         VARCHAR(32),
    consultant_name         VARCHAR(200),
    -- What preview saw, so confirm can detect changes made in between.
    existing_client_id      BIGINT REFERENCES clients (id),
    existing_client_version BIGINT,
    outcome                 VARCHAR(16),

    CONSTRAINT uq_import_rows_job_row UNIQUE (import_job_id, row_number),
    CONSTRAINT ck_import_rows_row_number CHECK (row_number > 0),
    CONSTRAINT ck_import_rows_action
        CHECK (action IN ('NEW', 'UPDATE', 'UNCHANGED', 'INVALID', 'CONFLICT', 'DUPLICATE')),
    CONSTRAINT ck_import_rows_outcome CHECK (outcome IS NULL OR outcome IN ('APPLIED', 'SKIPPED', 'STALE')),
    CONSTRAINT ck_import_rows_existing_for_update
        CHECK (action NOT IN ('UPDATE', 'UNCHANGED', 'CONFLICT') OR existing_client_id IS NOT NULL)
);

CREATE INDEX ix_import_rows_job_action ON import_rows (import_job_id, action);

-- Row-level errors and warnings (FR-12). Messages must never contain a full ID number.
CREATE TABLE import_errors
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id BIGINT       NOT NULL REFERENCES import_jobs (id) ON DELETE CASCADE,
    -- NULL for file-level problems (missing header, wrong sheet, ...).
    row_number    INTEGER,
    field_name    VARCHAR(64),
    error_code    VARCHAR(64)  NOT NULL,
    severity      VARCHAR(8)   NOT NULL,
    safe_message  VARCHAR(500) NOT NULL,

    CONSTRAINT ck_import_errors_severity CHECK (severity IN ('ERROR', 'WARNING')),
    CONSTRAINT ck_import_errors_row_number CHECK (row_number IS NULL OR row_number > 0),
    -- Last line of defence against leaking an ID number into a report.
    CONSTRAINT ck_import_errors_no_id_number CHECK (safe_message !~ '[0-9]{13}')
);

CREATE INDEX ix_import_errors_job ON import_errors (import_job_id, row_number);

-- Import traceability on the target tables.
ALTER TABLE clients
    ADD COLUMN created_by_import_job_id BIGINT REFERENCES import_jobs (id);

ALTER TABLE client_assignment_history
    ADD COLUMN import_job_id BIGINT REFERENCES import_jobs (id),
    ADD CONSTRAINT ck_assignment_history_import_has_job
        CHECK (change_type <> 'IMPORT' OR import_job_id IS NOT NULL);

CREATE INDEX ix_assignment_history_import_job ON client_assignment_history (import_job_id)
    WHERE import_job_id IS NOT NULL;
