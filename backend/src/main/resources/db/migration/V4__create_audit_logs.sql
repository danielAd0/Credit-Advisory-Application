
CREATE TABLE audit_logs
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users (id),
    action        VARCHAR(64) NOT NULL,
    target_type   VARCHAR(64),
    target_id     VARCHAR(64),
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata      JSONB       NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT ck_audit_logs_action_format CHECK (action ~ '^[A-Z][A-Z0-9_]{1,63}$'),
    CONSTRAINT ck_audit_logs_target_pair CHECK ((target_type IS NULL) = (target_id IS NULL)),
    CONSTRAINT ck_audit_logs_metadata_object CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX ix_audit_logs_target ON audit_logs (target_type, target_id, occurred_at DESC);
CREATE INDEX ix_audit_logs_actor ON audit_logs (actor_user_id, occurred_at DESC);
CREATE INDEX ix_audit_logs_occurred ON audit_logs (occurred_at DESC);

CREATE TRIGGER trg_audit_logs_no_update
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION reject_modification();

CREATE TRIGGER trg_audit_logs_no_truncate
    BEFORE TRUNCATE ON audit_logs
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();
