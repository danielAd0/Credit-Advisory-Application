-- =====================================================================
-- V14: the workbook's own Report and Breakdown figures (decision D1)
--
-- The app's reports are recalculated from the client rows (V15 views).
-- Each value the Report and Breakdown sheets showed is ALSO kept here,
-- cell by cell, with the recalculated value and the difference, so a
-- manager can check the import against the original workbook and see
-- which spreadsheet formulas were wrong.
--
-- Contains no client personal data: only totals, consultant / structure
-- labels and formulas.
-- =====================================================================

CREATE TABLE weekly_report_figures
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id     BIGINT        NOT NULL REFERENCES import_jobs (id),
    reporting_week_id BIGINT        NOT NULL REFERENCES reporting_weeks (id),
    sheet_name        VARCHAR(32)   NOT NULL,
    section           VARCHAR(32)   NOT NULL,
    block_title       VARCHAR(100),           -- as written in the sheet, e.g. 'CARD', 'Groceries'
    row_label         VARCHAR(200),           -- consultant / structure / day label as written
    column_label      VARCHAR(100),           -- 'MONDAY', 'TOTAL', 'VAT', ...
    day_of_week       SMALLINT,               -- 1..7 when the cell is for one day
    consultant_id     BIGINT REFERENCES consultants (id),
    product_id        BIGINT REFERENCES products (id),   -- what the formula ACTUALLY sums
    structure_id      BIGINT REFERENCES structures (id),
    cell_ref          VARCHAR(12)   NOT NULL, -- 'C14'
    sheet_value       NUMERIC(14, 2),
    sheet_text        VARCHAR(100),           -- 'Target Reached'
    sheet_error       VARCHAR(16),            -- '#REF!'
    sheet_formula     VARCHAR(2000),
    computed_value    NUMERIC(14, 2),
    computed_text     VARCHAR(100),
    difference        NUMERIC(14, 2),         -- sheet_value - computed_value
    matches           BOOLEAN,                -- NULL when there is nothing to compare
    defect_code       VARCHAR(32),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_report_figures_cell UNIQUE (import_job_id, sheet_name, cell_ref),
    CONSTRAINT ck_report_figures_sheet CHECK (sheet_name IN ('Report', 'Breakdown')),
    CONSTRAINT ck_report_figures_section CHECK (section IN (
        'DAILY_BANKED', 'DAILY_QUOTATION', 'DAILY_TARGET', 'DAILY_CLIENT_COUNT',
        'CONSULTANT_PRODUCT', 'CONSULTANT_CLIENT_COUNT', 'CONSULTANT_QUOTATION', 'CONSULTANT_TOTAL',
        'FINANCE', 'SHEET_DIFFERENCE', 'BUDGET_BY_STRUCTURE',
        'BREAKDOWN', 'BREAKDOWN_SUMMARY', 'OTHER')),
    CONSTRAINT ck_report_figures_day CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_report_figures_cell_ref CHECK (cell_ref ~ '^[A-Z]{1,3}[0-9]{1,7}$'),
    -- A cell holds a number, a text or an error - never more than one.
    CONSTRAINT ck_report_figures_one_value CHECK (
        (sheet_value IS NOT NULL)::int + (sheet_text IS NOT NULL)::int + (sheet_error IS NOT NULL)::int <= 1),
    CONSTRAINT ck_report_figures_error_format CHECK (sheet_error IS NULL OR sheet_error ~ '^#[A-Z0-9/]+[!?]?$'),
    CONSTRAINT ck_report_figures_difference CHECK (
        difference IS NULL OR (sheet_value IS NOT NULL AND computed_value IS NOT NULL)),
    CONSTRAINT ck_report_figures_defect CHECK (defect_code IS NULL OR defect_code IN (
        'WRONG_COLUMN', 'WRONG_CRITERIA_COLUMN', 'ROW_OFFSET', 'WRONG_SHEET', 'TEXT_ID_NOT_COUNTED',
        'RANGE_INCOMPLETE', 'REF_ERROR', 'VALUE_ERROR', 'BLANK_CONSULTANT_EXCLUDED',
        'THRESHOLD_GREATER_THAN', 'UNEXPLAINED'))
);

CREATE INDEX ix_report_figures_week ON weekly_report_figures (reporting_week_id, sheet_name, section);
CREATE INDEX ix_report_figures_differences ON weekly_report_figures (import_job_id)
    WHERE matches = FALSE OR sheet_error IS NOT NULL;

-- Figures are evidence of what the workbook said: never edited afterwards.
CREATE TRIGGER trg_report_figures_no_update
    BEFORE UPDATE ON weekly_report_figures
    FOR EACH ROW EXECUTE FUNCTION reject_modification();
