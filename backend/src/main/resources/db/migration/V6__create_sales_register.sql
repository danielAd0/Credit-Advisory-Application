CREATE TABLE employers
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_employers_name_not_blank CHECK (btrim(name) <> '')
);
CREATE UNIQUE INDEX uq_employers_name_ci ON employers (lower(btrim(name)));

CREATE TABLE structures
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_structures_name_not_blank CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX uq_structures_name_ci ON structures (lower(btrim(name)));

