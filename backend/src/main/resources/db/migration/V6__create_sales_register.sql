CREATE TABLE client_transaction_lines
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id          BIGINT         NOT NULL REFERENCES client_transactions (id) ON DELETE CASCADE,
    product_id              BIGINT         NOT NULL REFERENCES products (id),
    amount                  NUMERIC(12, 2) NOT NULL,

    counts_toward_quotation BOOLEAN        NOT NULL,
    counts_toward_banked    BOOLEAN        NOT NULL,

    CONSTRAINT uq_transaction_lines_product UNIQUE (transaction_id, product_id),
    CONSTRAINT ck_transaction_lines_amount CHECK (amount > 0)
);

CREATE INDEX ix_transaction_lines_product ON client_transaction_lines (product_id);


CREATE TABLE sales_targets
