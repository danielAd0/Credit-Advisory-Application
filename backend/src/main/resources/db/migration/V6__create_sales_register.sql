CREATE TABLE consultant_aliases
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultant_id      BIGINT       NOT NULL REFERENCES consultants (id),
    alias              VARCHAR(200) NOT NULL,
    created_by_user_id BIGINT       NOT NULL REFERENCES users (id),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_consultant_aliases_not_blank CHECK (btrim(alias) <> '')
);
CREATE UNIQUE INDEX uq_consultant_aliases_alias_ci
    ON consultant_aliases (lower(regexp_replace(btrim(alias), '\s+', ' ', 'g')));
CREATE INDEX ix_consultant_aliases_consultant ON consultant_aliases (consultant_id);


CREATE TABLE client_transactions
(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id                       BIGINT      NOT NULL REFERENCES clients (id),

    consultant_id                   BIGINT      NOT NULL REFERENCES consultants (id),
    transaction_date                DATE        NOT NULL,
    employer_id                     BIGINT REFERENCES employers (id),
    structure_id                    BIGINT REFERENCES structures (id),
    payment_term_id                 BIGINT REFERENCES payment_terms (id),
    amount_to_client                NUMERIC(12, 2),
    third_party_settlement          NUMERIC(12, 2),
    primary_structure_budget_list   VARCHAR(500),
    primary_structure_loan_amount   NUMERIC(12, 2),
    secondary_structure_budget_list VARCHAR(500),
    secondary_structure_loan_amount NUMERIC(12, 2),
    import_job_id                   BIGINT REFERENCES import_jobs (id),
    source_sheet                    VARCHAR(32),
    source_row_number               INTEGER,
    created_by_user_id              BIGINT      NOT NULL REFERENCES users (id),
    version                         BIGINT      NOT NULL DEFAULT 0,
    created_at                      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_transactions_amounts_not_negative CHECK (
        coalesce(amount_to_client, 0) >= 0 AND coalesce(third_party_settlement, 0) >= 0
            AND coalesce(primary_structure_loan_amount, 0) >= 0
            AND coalesce(secondary_structure_loan_amount, 0) >= 0),
    CONSTRAINT ck_transactions_source_complete CHECK (
        (import_job_id IS NULL AND source_sheet IS NULL AND source_row_number IS NULL)
            OR (import_job_id IS NOT NULL AND source_sheet IS NOT NULL AND source_row_number > 0)),
    CONSTRAINT uq_transactions_source UNIQUE (import_job_id, source_sheet, source_row_number)
);

CREATE INDEX ix_transactions_date ON client_transactions (transaction_date);
CREATE INDEX ix_transactions_consultant_date ON client_transactions (consultant_id, transaction_date);
CREATE INDEX ix_transactions_client_date ON client_transactions (client_id, transaction_date);
CREATE INDEX ix_transactions_employer ON client_transactions (employer_id);

CREATE TRIGGER trg_transactions_updated_at
    BEFORE UPDATE ON client_transactions
