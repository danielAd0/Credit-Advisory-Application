    created_at              TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uq_sales_targets_effective UNIQUE (effective_from),
    CONSTRAINT ck_sales_targets_positive CHECK (daily_quotation_target > 0)
);

