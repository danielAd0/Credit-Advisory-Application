
CREATE TABLE products
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(40)  NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    standard_price          NUMERIC(12, 2),
    counts_toward_quotation BOOLEAN      NOT NULL DEFAULT TRUE,
    counts_toward_banked    BOOLEAN      NOT NULL DEFAULT TRUE,
    active                  BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order           INTEGER      NOT NULL DEFAULT 0,
    version                 BIGINT       NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_products_code UNIQUE (code),
    CONSTRAINT ck_products_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{1,39}$'),
    CONSTRAINT ck_products_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_products_price CHECK (standard_price IS NULL OR standard_price >= 0)
);

CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


