-- =====================================================================
-- V20: client details the Clients page shows, and the product quotation list.
--
-- The launch client list (docs: "Initial client load") brings a work phone,
-- a home phone, the product quotation (its C_BRANCHNAME column), the old
-- File number and File ID, and "DEBIT ORDER" where the employer should be.
-- Consultants enter the same fields by hand, so every field is checked here
-- as well as in the application.
-- =====================================================================

-- Product quotations: a list admins manage, picked from a dropdown, so the
-- same quotation is never spelled two ways. Never deleted (clients point at
-- them); deactivated instead.
CREATE TABLE product_quotations
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_product_quotations_name_not_blank CHECK (btrim(name) <> '')
);

-- "Mafori Advance" and " mafori  advance" are the same quotation.
CREATE UNIQUE INDEX uq_product_quotations_name_ci ON product_quotations (lower(btrim(name)));

ALTER TABLE clients
    -- Same international format as the existing phone column (the cellphone).
    ADD COLUMN work_phone           VARCHAR(20),
    ADD COLUMN home_phone           VARCHAR(20),
    ADD COLUMN product_quotation_id BIGINT REFERENCES product_quotations (id),
    -- Text, not numbers: digits only, and a leading 0 must survive.
    ADD COLUMN file_number          VARCHAR(20),
    ADD COLUMN file_id              VARCHAR(20),
    -- How the client pays when it is not a payroll deduction. Only DEBIT_ORDER
    -- for now; a new method is one more value in this check.
    ADD COLUMN payment_method       VARCHAR(20),

    ADD CONSTRAINT ck_clients_work_phone_format CHECK (work_phone IS NULL OR work_phone ~ '^\+[1-9][0-9]{7,14}$'),
    ADD CONSTRAINT ck_clients_home_phone_format CHECK (home_phone IS NULL OR home_phone ~ '^\+[1-9][0-9]{7,14}$'),
    ADD CONSTRAINT ck_clients_file_number_digits CHECK (file_number IS NULL OR file_number ~ '^[0-9]{1,20}$'),
    ADD CONSTRAINT ck_clients_file_id_digits CHECK (file_id IS NULL OR file_id ~ '^[0-9]{1,20}$'),
    ADD CONSTRAINT ck_clients_payment_method CHECK (payment_method IS NULL OR payment_method IN ('DEBIT_ORDER'));

CREATE INDEX ix_clients_product_quotation ON clients (product_quotation_id);
-- Staff search by File number or File ID.
CREATE INDEX ix_clients_file_number ON clients (file_number) WHERE file_number IS NOT NULL;
CREATE INDEX ix_clients_file_id ON clients (file_id) WHERE file_id IS NOT NULL;

-- Vital is the only structure the business uses today. The structures table
-- stays a list, so more can be added later.
INSERT INTO structures (name)
VALUES ('Vital')
ON CONFLICT ((lower(btrim(name)))) DO NOTHING;
