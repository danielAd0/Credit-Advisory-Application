
ALTER TABLE consultants
    ADD COLUMN email VARCHAR(254);

ALTER TABLE consultants
    ADD CONSTRAINT ck_consultants_email_format
        CHECK (email IS NULL OR (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' AND email = lower(btrim(email))));

UPDATE consultants c
SET email = lower(btrim(u.email))
FROM users u
WHERE u.linked_consultant_id = c.id
  AND c.email IS NULL;

CREATE UNIQUE INDEX uq_consultants_email ON consultants (email) WHERE email IS NOT NULL;


