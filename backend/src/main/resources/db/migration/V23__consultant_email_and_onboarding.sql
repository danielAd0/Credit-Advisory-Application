CREATE TABLE consultant_login_invites
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultant_id        BIGINT       NOT NULL REFERENCES consultants (id),
    user_id              BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    email                VARCHAR(254) NOT NULL,
    password_sealed      BYTEA,
    status               VARCHAR(8)   NOT NULL DEFAULT 'PENDING',
    attempts             INTEGER      NOT NULL DEFAULT 0,
    last_error           VARCHAR(500),
    generated_by_user_id BIGINT       NOT NULL REFERENCES users (id),
    generated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    queued_by_user_id    BIGINT REFERENCES users (id),
    queued_at            TIMESTAMPTZ,
    next_attempt_at      TIMESTAMPTZ,
    last_attempt_at      TIMESTAMPTZ,
    sent_at              TIMESTAMPTZ,

    CONSTRAINT ck_invites_status CHECK (status IN ('PENDING', 'QUEUED', 'SENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_invites_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_invites_password_kept_until_sent CHECK ((status = 'SENT') = (password_sealed IS NULL)),
    CONSTRAINT ck_invites_sent_at CHECK ((status = 'SENT') = (sent_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_invites_user ON consultant_login_invites (user_id);
CREATE INDEX ix_invites_status ON consultant_login_invites (status, next_attempt_at);
CREATE INDEX ix_invites_consultant ON consultant_login_invites (consultant_id);
