-- =====================================================================
-- V13: weekly register import (docs/weekly-register-import-design.md)
--
-- * reporting_weeks: one row per Monday. Weeks are never overwritten; a
--   re-import supersedes the earlier import's transactions (kept, not deleted).
-- * client_transactions: the row's own Quotation / Banked as the sheet
--   calculated them (decision D3), the week and weekday, the consultant name
--   as written, and an optional consultant (decision D2: rows without one are
--   still imported).
-- * client_transaction_extras: every column the import does not recognise,
--   so nothing in the workbook is lost.
-- * employer_aliases + employers.needs_review: spellings from the register
--   ("PHUMELELA LOCAL") mapped to one employer.
-- * import_header_aliases: header spellings ("GROECRY") and sheet names
--   ("Wednsday") the parser accepts. Data, not code, so admins can extend it.
-- * sales_targets.weekly_quotation_target (the workbook's R600,000).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Reporting weeks
-- ---------------------------------------------------------------------
CREATE TABLE reporting_weeks
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_starting DATE        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_reporting_weeks_start UNIQUE (week_starting),
    CONSTRAINT ck_reporting_weeks_monday CHECK (extract(isodow FROM week_starting) = 1)
);

-- ---------------------------------------------------------------------
-- Import jobs: link to the week, replacement of an earlier import, outcome
-- ---------------------------------------------------------------------
ALTER TABLE import_jobs
    ADD COLUMN reporting_week_id      BIGINT REFERENCES reporting_weeks (id),
    ADD COLUMN replaces_import_job_id BIGINT REFERENCES import_jobs (id),
    ADD COLUMN replace_reason         VARCHAR(500),
    ADD COLUMN warning_count          INTEGER     NOT NULL DEFAULT 0,
    ADD COLUMN reconciliation_status  VARCHAR(16) NOT NULL DEFAULT 'NOT_CHECKED',
    ADD COLUMN reconciliation_differences INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_import_jobs_reconciliation
        CHECK (reconciliation_status IN ('NOT_CHECKED', 'MATCHED', 'DIFFERENCES')),
    ADD CONSTRAINT ck_import_jobs_warning_count CHECK (warning_count >= 0 AND reconciliation_differences >= 0),
    -- A replacement must say why (design 4.9).
    ADD CONSTRAINT ck_import_jobs_replace_reason
        CHECK (replaces_import_job_id IS NULL OR (replace_reason IS NOT NULL AND btrim(replace_reason) <> '')),
    ADD CONSTRAINT ck_import_jobs_not_self_replacing CHECK (replaces_import_job_id IS DISTINCT FROM id),
    -- Weekly imports belong to a week. (week_starting from V9 stays as the requested Monday.)
    ADD CONSTRAINT ck_import_jobs_weekly_has_week
        CHECK (import_type <> 'WEEKLY_REGISTER' OR state <> 'COMMITTED' OR reporting_week_id IS NOT NULL);

-- At most one committed, not-yet-replaced import per week is enforced by the
-- service together with this index: confirm locks the week row first.
CREATE INDEX ix_import_jobs_week ON import_jobs (reporting_week_id, state);

-- Which committed import a week currently shows (NULL until the first confirm).
ALTER TABLE reporting_weeks
    ADD COLUMN current_import_job_id BIGINT REFERENCES import_jobs (id);

-- ---------------------------------------------------------------------
-- Transactions
-- ---------------------------------------------------------------------
ALTER TABLE client_transactions
    -- D2: a register row without a consultant is still a real sale.
    ALTER COLUMN consultant_id DROP NOT NULL,
    ADD COLUMN reporting_week_id           BIGINT REFERENCES reporting_weeks (id),
    -- ISO weekday of transaction_date: 1 = Monday ... 7 = Sunday.
    ADD COLUMN day_of_week                 SMALLINT,
    -- D3: the values the sheet calculated for this row, kept exactly.
    ADD COLUMN quotation_amount            NUMERIC(12, 2),
    ADD COLUMN banked_amount               NUMERIC(12, 2),
    -- As written in the sheet, for review and for mapping later.
    ADD COLUMN source_consultant_name      VARCHAR(200),
    ADD COLUMN source_employer_name        VARCHAR(200),
    -- Set when a later import of the same week replaces this one (design 4.9).
    ADD COLUMN superseded_by_import_job_id BIGINT REFERENCES import_jobs (id),
    ADD CONSTRAINT ck_transactions_day_of_week
        CHECK (day_of_week IS NULL OR (day_of_week BETWEEN 1 AND 7
            AND day_of_week = extract(isodow FROM transaction_date))),
    ADD CONSTRAINT ck_transactions_week_has_day
        CHECK (reporting_week_id IS NULL OR day_of_week IS NOT NULL),
    ADD CONSTRAINT ck_transactions_source_amounts_not_negative
        CHECK (coalesce(quotation_amount, 0) >= 0 AND coalesce(banked_amount, 0) >= 0),
    ADD CONSTRAINT ck_transactions_superseded_imported
        CHECK (superseded_by_import_job_id IS NULL OR import_job_id IS NOT NULL);

CREATE INDEX ix_transactions_week_day ON client_transactions (reporting_week_id, day_of_week)
    WHERE superseded_by_import_job_id IS NULL;
CREATE INDEX ix_transactions_unattributed ON client_transactions (reporting_week_id)
    WHERE consultant_id IS NULL;

-- transaction_date must fall inside its reporting week. A CHECK cannot read
-- another table, so a trigger does it.
CREATE FUNCTION ensure_transaction_in_week() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    monday DATE;
BEGIN
    IF NEW.reporting_week_id IS NOT NULL THEN
        SELECT week_starting INTO monday FROM reporting_weeks WHERE id = NEW.reporting_week_id;
        IF NEW.transaction_date < monday OR NEW.transaction_date > monday + 6 THEN
            RAISE EXCEPTION 'Transaction date is outside its reporting week'
                USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_transactions_in_week';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_transactions_in_week
    BEFORE INSERT OR UPDATE OF transaction_date, reporting_week_id ON client_transactions
    FOR EACH ROW EXECUTE FUNCTION ensure_transaction_in_week();

-- Columns the import did not recognise (design 4.7). Never discarded.
CREATE TABLE client_transaction_extras
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT       NOT NULL REFERENCES client_transactions (id) ON DELETE CASCADE,
    sheet_header   VARCHAR(100) NOT NULL,
    value_text     VARCHAR(500),
    value_number   NUMERIC(14, 2),

    CONSTRAINT uq_transaction_extras_header UNIQUE (transaction_id, sheet_header),
    CONSTRAINT ck_transaction_extras_header_not_blank CHECK (btrim(sheet_header) <> ''),
    CONSTRAINT ck_transaction_extras_has_value CHECK (value_text IS NOT NULL OR value_number IS NOT NULL),
    -- Same last line of defence as import_errors: never a full ID number here.
    CONSTRAINT ck_transaction_extras_no_id_number CHECK (value_text IS NULL OR value_text !~ '[0-9]{13}')
);

-- ---------------------------------------------------------------------
-- Employers seen in the register
-- ---------------------------------------------------------------------
ALTER TABLE employers
    -- TRUE when the import created it from an unknown spelling; an admin
    -- confirms it or merges it into an existing employer (which adds an alias).
    ADD COLUMN needs_review BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX ix_employers_needs_review ON employers (id) WHERE needs_review;

CREATE TABLE employer_aliases
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id        BIGINT       NOT NULL REFERENCES employers (id),
    alias              VARCHAR(200) NOT NULL,
    created_by_user_id BIGINT REFERENCES users (id),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_employer_aliases_not_blank CHECK (btrim(alias) <> '')
);

CREATE UNIQUE INDEX uq_employer_aliases_alias_ci
    ON employer_aliases (lower(regexp_replace(btrim(alias), '\s+', ' ', 'g')));
CREATE INDEX ix_employer_aliases_employer ON employer_aliases (employer_id);

-- ---------------------------------------------------------------------
-- Header and sheet-name spellings the parser accepts (design 3)
-- ---------------------------------------------------------------------
CREATE TABLE import_header_aliases
(
    alias     VARCHAR(100) PRIMARY KEY,   -- upper-case, single-spaced
    canonical VARCHAR(100) NOT NULL,      -- product code, field name or weekday
    kind      VARCHAR(8)   NOT NULL,

    CONSTRAINT ck_header_aliases_kind CHECK (kind IN ('PRODUCT', 'FIELD', 'SHEET')),
    CONSTRAINT ck_header_aliases_alias_format CHECK (alias = upper(alias) AND alias = btrim(alias)
        AND alias !~ '\s{2,}'),
    CONSTRAINT ck_header_aliases_sheet_day CHECK (kind <> 'SHEET' OR canonical IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

