-- ---------------------------------------------------------------------
-- Targets: the workbook also has a weekly target (R600,000)
-- ---------------------------------------------------------------------
ALTER TABLE sales_targets
    ADD COLUMN weekly_quotation_target NUMERIC(12, 2),
    ADD CONSTRAINT ck_sales_targets_weekly_positive
        CHECK (weekly_quotation_target IS NULL OR weekly_quotation_target > 0);

UPDATE sales_targets
SET weekly_quotation_target = 600000.00
WHERE effective_from = DATE '2026-01-01'
  AND weekly_quotation_target IS NULL;

-- ---------------------------------------------------------------------
-- Staging rows and issues
-- ---------------------------------------------------------------------
ALTER TABLE import_rows
    ADD COLUMN day_of_week   SMALLINT,
    -- Unrecognised columns of this row, e.g. {"Column V": "x"} (personal-data free; purged with the row).
    ADD COLUMN extras        JSONB,
    ADD COLUMN warning_count INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_import_rows_day CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),
    ADD CONSTRAINT ck_import_rows_extras_object CHECK (extras IS NULL OR jsonb_typeof(extras) = 'object'),
    ADD CONSTRAINT ck_import_rows_warning_count CHECK (warning_count >= 0);

-- Informational lines ("new structure created", "client appears twice") next to errors and warnings.
ALTER TABLE import_errors
    DROP CONSTRAINT ck_import_errors_severity,
    ADD CONSTRAINT ck_import_errors_severity CHECK (severity IN ('ERROR', 'WARNING', 'INFO'));
