

ALTER TABLE import_jobs
    ADD COLUMN import_type      VARCHAR(20) NOT NULL DEFAULT 'CLIENT_LIST',
    ADD COLUMN week_starting    DATE,
    ADD COLUMN new_client_count INTEGER     NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_import_jobs_type CHECK (import_type IN ('CLIENT_LIST', 'WEEKLY_REGISTER')),
    ADD CONSTRAINT ck_import_jobs_week CHECK ((import_type = 'WEEKLY_REGISTER') = (week_starting IS NOT NULL)),
    ADD CONSTRAINT ck_import_jobs_week_monday CHECK (week_starting IS NULL OR extract(isodow FROM week_starting) = 1),
    ADD CONSTRAINT ck_import_jobs_new_clients CHECK (new_client_count >= 0);

ALTER TABLE import_rows
    DROP CONSTRAINT uq_import_rows_job_row;

ALTER TABLE import_rows
    ADD COLUMN sheet_name             VARCHAR(32),
    ADD COLUMN transaction_date       DATE,
    ADD COLUMN creates_client         BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN assigns_consultant     BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN structure_name         VARCHAR(200),
    ADD COLUMN payment_term_code      VARCHAR(40),
    ADD COLUMN amount_to_client       NUMERIC(12, 2),
    ADD COLUMN third_party_settlement NUMERIC(12, 2),
    ADD COLUMN primary_budget_list    VARCHAR(500),
    ADD COLUMN primary_loan_amount    NUMERIC(12, 2),
    ADD COLUMN secondary_budget_list  VARCHAR(500),
    ADD COLUMN secondary_loan_amount  NUMERIC(12, 2),
    ADD COLUMN quotation_total        NUMERIC(14, 2),
    ADD COLUMN banked_total           NUMERIC(14, 2),
    ADD CONSTRAINT ck_import_rows_assign_needs_create CHECK (NOT assigns_consultant OR creates_client),
    ADD CONSTRAINT ck_import_rows_weekly_date CHECK (sheet_name IS NULL OR transaction_date IS NOT NULL);

CREATE UNIQUE INDEX uq_import_rows_job_sheet_row
    ON import_rows (import_job_id, coalesce(sheet_name, ''), row_number);

CREATE TABLE import_row_lines
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_row_id BIGINT         NOT NULL REFERENCES import_rows (id) ON DELETE CASCADE,
    product_id    BIGINT         NOT NULL REFERENCES products (id),
    amount        NUMERIC(12, 2) NOT NULL,

    CONSTRAINT uq_import_row_lines_product UNIQUE (import_row_id, product_id),
    CONSTRAINT ck_import_row_lines_amount CHECK (amount > 0)
);

ALTER TABLE import_errors
    ADD COLUMN sheet_name VARCHAR(32);

DROP INDEX ix_import_errors_job;
CREATE INDEX ix_import_errors_job ON import_errors (import_job_id, sheet_name, row_number);

CREATE INDEX ix_transactions_dedupe ON client_transactions (client_id, transaction_date, consultant_id);
