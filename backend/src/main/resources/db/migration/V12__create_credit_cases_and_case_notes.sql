-- =====================================================================
-- V12: credit advisory cases and case notes (FR-19, FR-15)
--
-- A case belongs to a CLIENT, never to a consultant. When a client is
-- transferred, the new consultant sees every case and note, and each note
-- keeps its original author.
--
-- Cases are never deleted. Notes are append-only: they cannot be edited
-- or deleted (a correction is a new note).
-- =====================================================================

CREATE TABLE credit_cases
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id          BIGINT       NOT NULL REFERENCES clients (id),
    title              VARCHAR(200) NOT NULL,
    status             VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    opened_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at          TIMESTAMPTZ,
    created_by_user_id BIGINT       NOT NULL REFERENCES users (id),
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_credit_cases_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
    CONSTRAINT ck_credit_cases_title_not_blank CHECK (btrim(title) <> ''),
    -- closed_at is set exactly when the case is CLOSED
    CONSTRAINT ck_credit_cases_closed_at CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT ck_credit_cases_closed_after_opened CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

CREATE INDEX ix_credit_cases_client ON credit_cases (client_id, opened_at DESC);
CREATE INDEX ix_credit_cases_status ON credit_cases (status);

CREATE TRIGGER trg_credit_cases_updated_at
    BEFORE UPDATE ON credit_cases
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- A case is closed, never deleted.
CREATE TRIGGER trg_credit_cases_no_delete
    BEFORE DELETE ON credit_cases
    FOR EACH ROW EXECUTE FUNCTION reject_modification();

CREATE TRIGGER trg_credit_cases_no_truncate
    BEFORE TRUNCATE ON credit_cases
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();


CREATE TABLE case_notes
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        BIGINT        NOT NULL REFERENCES credit_cases (id),
    author_user_id BIGINT        NOT NULL REFERENCES users (id),
    note           VARCHAR(4000) NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_case_notes_not_blank CHECK (btrim(note) <> '')
);

CREATE INDEX ix_case_notes_case ON case_notes (case_id, created_at DESC);

CREATE TRIGGER trg_case_notes_no_update
    BEFORE UPDATE OR DELETE ON case_notes
    FOR EACH ROW EXECUTE FUNCTION reject_modification();

CREATE TRIGGER trg_case_notes_no_truncate
    BEFORE TRUNCATE ON case_notes
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();
